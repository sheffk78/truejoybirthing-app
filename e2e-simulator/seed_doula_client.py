#!/opt/homebrew/bin/python3
"""Seed the E2E doula client for the doula contract flow (10/14).

Creates client 'E2E Doula Mom' on the local test backend via the real API
(POST /doula/clients), linked to testmom@test.com so the mom-side sign leg
authorizes. If the API doesn't stitch linked_mom_id, patches the test-DB doc
directly. Also emits maestro/fetch_doula_client.js + resolve_doula_draft.js
with the CURRENT legacy-draft exclusion list baked in (the doula account has
25 legacy Draft contracts from Aug; resolve must ignore them).
"""
import json, os, sys, urllib.request
from datetime import datetime, timezone

BASE = "http://127.0.0.1:8011"
HERE = os.path.dirname(os.path.abspath(__file__))
MAESTRO = os.path.join(HERE, "maestro")

def req(method, path, token=None, payload=None):
    data = json.dumps(payload).encode() if payload is not None else None
    r = urllib.request.Request(BASE + path, data=data, method=method)
    r.add_header("Content-Type", "application/json")
    if token:
        r.add_header("Authorization", "Bearer " + token)
    with urllib.request.urlopen(r, timeout=15) as resp:
        return json.loads(resp.read())

doula = req("POST", "/api/auth/login", payload={"email": "testdoula123@test.com", "password": "password123"})
dtok = doula["session_token"]
mom = req("POST", "/api/auth/login", payload={"email": "testmom@test.com", "password": "password123"})
mtok = mom["session_token"]
print("doula logged in:", doula["user_id"], "| mom logged in:", mom["user_id"])

# 1) find-or-create the E2E client
clients = req("GET", "/api/doula/clients", token=dtok)
client = next((c for c in clients if c.get("name") == "E2E Doula Mom"), None)
if not client:
    client = req("POST", "/api/doula/clients", token=dtok, payload={
        "name": "E2E Doula Mom",
        "email": "testmom@test.com",
        "estimated_due_date": "2030-03-15",
        "planned_birth_setting": "Home Birth",
        "notes": "E2E seeded client — doula contract flow",
    })
    print("created client:", client.get("client_id"))
else:
    print("client exists:", client.get("client_id"))
cid = client["client_id"]

# 2) ensure the mom link (needed for mom-side sign authorization)
if not client.get("linked_mom_id"):
    mid = mom["user_id"]
    try:
        req("PUT", f"/api/doula/clients/{cid}", token=dtok, payload={"linked_mom_id": mid})
        print("linked mom via API:", mid)
    except Exception as e:
        print("API link failed (", e, ") — direct test-DB patch")
        from pymongo import MongoClient
        c = MongoClient(os.environ.get("MONGO_URL", "mongodb://localhost:27017"))
        c["truejoybirthing_test"]["clients"].update_one({"client_id": cid}, {"$set": {"linked_mom_id": mid}})
        print("linked mom via Mongo patch:", mid)

# 3) capture legacy doula Draft ids (exclusion list for resolution)
contracts = req("GET", "/api/doula/contracts", token=dtok)
legacy = [c["contract_id"] for c in contracts if c.get("status") == "Draft"]
print("legacy Draft contracts excluded:", len(legacy))
with open(os.path.expanduser("~/.hermes/scripts/doula_legacy_drafts.json"), "w") as jf:
    json.dump(legacy, jf)

# 4) emit fetch_doula_client.js
fetch_js = """// AUTO-GENERATED by seed_doula_client.py — resolves the E2E doula client id.
const login = http.post("http://127.0.0.1:8011/api/auth/login", {
  headers: { "Content-Type": "application/json" },
  body: JSON.stringify({ email: "testdoula123@test.com", password: "password123" }),
});
const token = json(login.body).session_token;
if (!token) throw new Error("doula login failed");
const res = http.get("http://127.0.0.1:8011/api/doula/clients", {
  headers: { Authorization: "Bearer " + token },
});
const list = json(res.body);
var e2e = null;
for (var i = 0; i < list.length; i++) {
  if (list[i].name === "E2E Doula Mom") { e2e = list[i]; break; }
}
if (!e2e) throw new Error("E2E Doula Mom not found");
output.rowId = "client-row-" + e2e.client_id;
output.clientId = e2e.client_id;
"""
with open(os.path.join(MAESTRO, "fetch_doula_client.js"), "w") as f:
    f.write(fetch_js)

# 5) emit resolve_doula_draft.js (excludes legacy drafts hard-coded)
legacy_js = json.dumps(legacy)
resolve_js = """// AUTO-GENERATED by seed_doula_client.py — resolve THIS run's new Draft.
const LEGACY = %s;
const login = http.post("http://127.0.0.1:8011/api/auth/login", {
  headers: { "Content-Type": "application/json" },
  body: JSON.stringify({ email: "testdoula123@test.com", password: "password123" }),
});
const token = json(login.body).session_token;
if (!token) throw new Error("doula login failed");
const res = http.get("http://127.0.0.1:8011/api/doula/contracts", {
  headers: { Authorization: "Bearer " + token },
});
const list = json(res.body);
var fresh = [];
for (var i = 0; i < list.length; i++) {
  if (list[i].status === "Draft" && LEGACY.indexOf(list[i].contract_id) === -1) fresh.push(list[i]);
}
if (fresh.length === 0) throw new Error("no NEW draft contract found after create");
if (fresh.length > 1) throw new Error("expected 1 new draft, found " + fresh.length);
output.contractId = fresh[0].contract_id;
output.signingToken = "";
""" % legacy_js
with open(os.path.join(MAESTRO, "resolve_doula_draft.js"), "w") as f:
    f.write(resolve_js)

# 6) emit assert_doula_signed.js
assert_js = """// AUTO-GENERATED by seed_doula_client.py — assert THIS run's contract signed.
const login = http.post("http://127.0.0.1:8011/api/auth/login", {
  headers: { "Content-Type": "application/json" },
  body: JSON.stringify({ email: "testdoula123@test.com", password: "password123" }),
});
const token = json(login.body).session_token;
if (!token) throw new Error("doula login failed");
const res = http.get("http://127.0.0.1:8011/api/doula/contracts", {
  headers: { Authorization: "Bearer " + token },
});
const list = json(res.body);
var mine = null;
for (var i = 0; i < list.length; i++) {
  if (list[i].contract_id === output.contractId) { mine = list[i]; break; }
}
if (!mine) throw new Error("sign assertion: contract not found");
if (mine.status !== "Signed")
  throw new Error("sign assertion FAILED: status=" + mine.status + " — API sign did not succeed");
if (mine.client_signature && mine.client_signature.signer_name && mine.client_signature.signer_name !== "Test Mom")
  throw new Error("sign assertion FAILED: signer_name=" + mine.client_signature.signer_name);
"""
with open(os.path.join(MAESTRO, "assert_doula_signed.js"), "w") as f:
    f.write(assert_js)

print("emitted: fetch_doula_client.js / resolve_doula_draft.js / assert_doula_signed.js")
print("CLIENT_ID:", cid)